/**
 * Embeds the Apple Wallet pass images into a TypeScript module.
 *
 * The pass is assembled in memory inside the route handler, so its images
 * have to travel with the code rather than being read off disk at request
 * time. Re-run this after changing anything in public/embassy/pass.
 *
 *   node scripts/build-pass-assets.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const dir = join(root, 'public/embassy/pass')
const files = ['icon.png', 'icon@2x.png', 'logo.png', 'logo@2x.png']

let out = `/* Generated by scripts/build-pass-assets.mjs — do not edit by hand. */

export const PASS_IMAGES: Record<string, Buffer> = {
`
for (const f of files) {
  const b64 = readFileSync(join(dir, f)).toString('base64')
  out += `  ${JSON.stringify(f)}: Buffer.from(${JSON.stringify(b64)}, 'base64'),\n`
}
out += '}\n'

writeFileSync(join(root, 'lib/embassy/pass-assets.ts'), out)
console.log(`wrote lib/embassy/pass-assets.ts (${(out.length / 1024).toFixed(1)} KB)`)
